/* Categories, their labels and order, and the rule views all come from the rule
   catalog (D.G, generated by ts_cli/audit/generate.py report_meta) — never listed here.
   ANGLE_* keep the legacy `angle` keys ("ai", "data_modeling", …) that findings carry. */
var CATEGORIES = (D.G && D.G.categories) || [];
var CATEGORY_IDS = [];
var ANGLE_LABELS = {}, ANGLE_SHORT = {}, ANGLE_CODES = {}, ANGLE_FULL_NAMES = {};
CATEGORIES.forEach(function(c){
  CATEGORY_IDS.push(c.id);
  ANGLE_LABELS[c.angle_key] = c.label;
  ANGLE_SHORT[c.id] = c.angle_key;
  ANGLE_CODES[c.angle_key] = c.id;
  ANGLE_FULL_NAMES[c.id] = c.label;
});
var VIEWS = (D.G && D.G.views) || {};
